-- Operational history for pooled loads, bids, bookings, and state transitions.
create table if not exists public.load_events (
  event_id bigint generated by default as identity primary key,
  load_id integer not null references public.loads(load_id) on delete cascade,
  actor_user_id integer,
  event_type text not null,
  entity_type text not null default 'load',
  entity_id integer,
  from_status text,
  to_status text,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists load_events_load_created_idx
  on public.load_events(load_id, created_at desc);
create index if not exists load_events_entity_idx
  on public.load_events(entity_type, entity_id, created_at desc);

-- Retries must be idempotent at the database boundary too.
create unique index if not exists bids_load_driver_vehicle_unique_idx
  on public.bids(load_id, driver_id, vehicle_id)
  where driver_id is not null and vehicle_id is not null;
create unique index if not exists bookings_active_vehicle_unique_idx
  on public.bookings(vehicle_id)
  where status in ('booked', 'in_transit');

alter table if exists public.load_events enable row level security;

-- Account role rows are provisioned by the application after Auth signup. The
-- old trigger created duplicate shipper records and made signup rollback unsafe.
drop trigger if exists after_user_insert on public.profiles;
